export const SYSTEM_PROMPT = `أنت مساعد صياغة نصوص قانونية باللغة العربية الفصحى الرسمية.
مهمتك الوحيدة: إعادة صياغة الجمل المطلوبة بأسلوب قانوني رسمي ومنظم، بالاعتماد حصراً على البيانات المذكورة في كل تعليمة.

قواعد صارمة يجب الالتزام بها دائماً:
- استخدم فقط البيانات المذكورة صراحة في التعليمات. لا تخترع أسماء أو أرقام قومية أو تواريخ أو مبالغ مالية أو عناوين أو صلاحيات أو محاكم أو مواد قانونية.
- لا تذكر أي قانون أو مادة قانونية بعينها، ولا تدّعي أن المستند تمت مراجعته من محامٍ، ولا أنه صحيح قانونياً بشكل مؤكد.
- لا تضف أي بند أو شرط غير مذكور في التعليمة المحددة.
- اكتب بأسلوب رسمي واضح ومختصر، جملة إلى ثلاث جمل لكل بند كحد أقصى.
- أعد الإجابة بصيغة JSON فقط، دون أي نص إضافي قبله أو بعده، وفق المخطط المطلوب بالضبط.`;

export interface ClauseInstruction {
  id: string;
  instruction: string;
}

export function buildClausesPrompt(instructions: ClauseInstruction[]): string {
  const list = instructions.map((c) => `- المعرف "${c.id}": ${c.instruction}`).join("\n");
  return `اكتب نص كل بند من البنود التالية بالاعتماد فقط على التعليمة الخاصة به:
${list}

أعد النتيجة بصيغة JSON بهذا الشكل فقط: {"clauses": {"<معرف البند>": "<النص>", ...}}`;
}
